"""Generate offline Flutter legal text from the same data as public pages.

Run after editing website/content/legal/*.json. No network or credentials.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]

def dart(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')

lines = ["// Generated by scripts/sync-legal-documents.py; edit website/content/legal instead.", "import 'legal_document.dart';", ""]
for slug, name in [('terms', 'termsOfService'), ('refunds', 'refundPolicy')]:
    data = json.loads((root / f'website/content/legal/{slug}.json').read_text())
    lines += [f'const {name} = LegalDocument(', f'  title: {dart(data["title"])},', f'  lastUpdated: {dart(data["updated"])},', "  summaryLead: 'The short version.',", f'  summary: {dart(data["summary"])},', '  sections: [']
    for section in data['sections']:
        lines.append(f'    LegalSection({dart(section["heading"])}, {dart(section["body"])}),')
    lines += ['  ],', ');', '']
(root / 'app/lib/features/settings/models/legal_documents.dart').write_text('\n'.join(lines))
